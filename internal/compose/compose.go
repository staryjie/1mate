var slugPattern = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{1,30}$`)

// ValidateSlug enforces the naming rule for remote directories and projects.
func ValidateSlug(slug string) error {
	if !slugPattern.MatchString(slug) {
		return errors.New("slug must be 2-31 lowercase letters, digits or dashes and start with a letter or digit")
	}
	if strings.HasSuffix(slug, "-") {
		return errors.New("slug must not end with a dash")
	}
	return nil
}

// Spec is the resolved input for both the compose file and the env file.
type Spec struct {
	Slug             string
	ProjectName      string
	BindAddress      string
	TMPort           int
	GrafanaPort      int
	MQTTPort         int
	Timezone         string
	Region           string
	ImageTag         string
	PostgresTag      string
	GrafanaAdminUser string
	DisableMQTT      bool
	ExtraEnv         map[string]string

	EncryptionKey   string
	DBUser          string
	DBPass          string
	GrafanaPassword string
}

// RegionHosts returns the Tesla API endpoints for a region preset.
func RegionHosts(region string) (api, auth, wss string) {
	switch region {
	case "cn":
		return "https://owner-api.vn.cloud.tesla.cn",
			"https://auth.tesla.cn",
			"wss://streaming.vn.cloud.tesla.cn/streaming"
	}
	return "", "", ""
}

// RenderEnv builds the .env file. Compose v1 and v2 both read it; all secrets
// live here and the compose file only references variables.
func RenderEnv(s Spec) (string, error) {
	vars := [][2]string{
		{"TM_ENCRYPTION_KEY", s.EncryptionKey},
		{"TM_DB_USER", s.DBUser},
		{"TM_DB_PASS", s.DBPass},
		{"TM_DB_NAME", "teslamate_" + strings.ReplaceAll(s.Slug, "-", "_")},
		{"GRAFANA_USER", s.GrafanaAdminUser},
		{"GRAFANA_PW", s.GrafanaPassword},
		{"TM_TZ", s.Timezone},
		{"TM_TM_PORT", strconv.Itoa(s.TMPort)},
		{"TM_GRAFANA_PORT", strconv.Itoa(s.GrafanaPort)},
		{"TM_MQTT_PORT", strconv.Itoa(s.MQTTPort)},
		{"TM_BIND", s.BindAddress},
		{"TM_IMAGE_TAG", s.ImageTag},
		{"TM_PG_TAG", s.PostgresTag},
	}
	api, auth, wss := RegionHosts(s.Region)
	vars = append(vars, [2]string{"TM_REGION", s.Region}, [2]string{"TM_API_HOST", api},
		[2]string{"TM_AUTH_HOST", auth}, [2]string{"TM_WSS_HOST", wss})
	if s.DisableMQTT {
		vars = append(vars, [2]string{"TM_DISABLE_MQTT", "true"})
	} else {
		vars = append(vars, [2]string{"TM_DISABLE_MQTT", "false"})
	}
	for _, k := range sortedKeys(s.ExtraEnv) {
		if err := validateEnvKey(k); err != nil {
			return "", err
		}
		vars = append(vars, [2]string{k, s.ExtraEnv[k]})
	}

	var b strings.Builder
	b.WriteString("# Generated by 1mate. Do not edit by hand; changes are overwritten on deploy.\n")
	for _, kv := range vars {
		fmt.Fprintf(&b, "%s=%s\n", kv[0], quoteEnv(kv[1]))
	}
	return b.String(), nil
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func validateEnvKey(k string) error {
	ok, _ := regexp.MatchString(`^[A-Z][A-Z0-9_]{2,63}$`, k)
	if !ok {
		return fmt.Errorf("invalid environment variable name %q", k)
	}
	switch k {
	case "TM_ENCRYPTION_KEY", "TM_DB_PASS", "TM_DB_USER", "GRAFANA_PW", "GRAFANA_USER",
		"TM_TM_PORT", "TM_GRAFANA_PORT", "TM_MQTT_PORT", "TM_BIND":
		return fmt.Errorf("environment variable %s is managed by 1mate and cannot be overridden", k)
	}
	return nil
}

func quoteEnv(v string) string {
	needs := strings.ContainsAny(v, " \t\"'$#\\\n")
	if !needs {
		return v
	}
	v = strings.ReplaceAll(v, `\`, `\\`)
	v = strings.ReplaceAll(v, `"`, `\"`)
	v = strings.ReplaceAll(v, "\n", " ")
	return `"` + v + `"`
}

// Render generates the compose file for the requested major version.
func Render(s Spec, major int) (string, error) {
	if major != 1 && major != 2 {
		return "", fmt.Errorf("unsupported compose major version %d", major)
	}
	if err := ValidateSlug(s.Slug); err != nil {
		return "", err
	}
	for name, p := range map[string]int{"teslamate": s.TMPort, "grafana": s.GrafanaPort, "mqtt": s.MQTTPort} {
		if p < 1 || p > 65535 {
			return "", fmt.Errorf("%s port %d is out of range", name, p)
		}
	}
	if err := validateBind(s.BindAddress); err != nil {
		return "", err
	}
	if s.EncryptionKey == "" || s.DBPass == "" || s.GrafanaPassword == "" {
		return "", errors.New("secrets must be set before rendering")
	}

	var b strings.Builder
	if major == 1 {
		b.WriteString("# Generated by 1mate for Docker Compose v1 (legacy).\n")
		b.WriteString("version: \"3.9\"\n\n")
	} else {
		b.WriteString("# Generated by 1mate for Docker Compose v2.\n")
		fmt.Fprintf(&b, "name: %s\n\n", s.ProjectName)
	}
	b.WriteString("services:\n")
	b.WriteString(renderTeslaMate(s))
	b.WriteString(renderDatabase(s))
	b.WriteString(renderGrafana(s))
	b.WriteString(renderMosquitto(s))
	b.WriteString("\nvolumes:\n")
	b.WriteString("  teslamate-db:\n  teslamate-grafana-data:\n  mosquitto-conf:\n  mosquitto-data:\n")
	return b.String(), nil
}

func validateBind(addr string) error {
	if addr == "" {
		return nil
	}
	if ip := net.ParseIP(addr); ip == nil {
		return fmt.Errorf("bind address %q is not a valid IP", addr)
	}
	return nil
}

func renderTeslaMate(s Spec) string {
	var b strings.Builder
	b.WriteString("  teslamate:\n")
	fmt.Fprintf(&b, "    image: teslamate/teslamate:${TM_IMAGE_TAG}\n")
	b.WriteString("    restart: always\n")
	b.WriteString("    depends_on:\n      - database\n")
	b.WriteString("    environment:\n")
	writeEnvRefs(&b, []string{
		"ENCRYPTION_KEY=${TM_ENCRYPTION_KEY}",
		"DATABASE_USER=${TM_DB_USER}",
		"DATABASE_PASS=${TM_DB_PASS}",
		"DATABASE_NAME=${TM_DB_NAME}",
		"DATABASE_HOST=database",
		"TZ=${TM_TZ}",
		"CHECK_ORIGIN=true",
		"DISABLE_MQTT=${TM_DISABLE_MQTT}",
		"TESLA_API_HOST=${TM_API_HOST}",
		"TESLA_AUTH_HOST=${TM_AUTH_HOST}",
		"TESLA_WSS_HOST=${TM_WSS_HOST}",
	})
	if !s.DisableMQTT {
		writeEnvRefs(&b, []string{"MQTT_HOST=mosquitto"})
	}
	b.WriteString("    ports:\n")
	fmt.Fprintf(&b, "      - \"${TM_BIND}:${TM_TM_PORT}:4000\"\n")
	b.WriteString("    volumes:\n      - ./import:/opt/app/import\n")
	b.WriteString("    cap_drop:\n      - all\n")
	return b.String()
}

func renderDatabase(s Spec) string {
	var b strings.Builder
	b.WriteString("\n  database:\n")
	fmt.Fprintf(&b, "    image: postgres:${TM_PG_TAG}\n")
	b.WriteString("    restart: always\n")
	b.WriteString("    environment:\n")
	writeEnvRefs(&b, []string{
		"POSTGRES_USER=${TM_DB_USER}",
		"POSTGRES_PASSWORD=${TM_DB_PASS}",
		"POSTGRES_DB=${TM_DB_NAME}",
	})
	b.WriteString("    volumes:\n      - teslamate-db:/var/lib/postgresql\n")
	return b.String()
}

func renderGrafana(s Spec) string {
	var b strings.Builder
	b.WriteString("\n  grafana:\n")
	fmt.Fprintf(&b, "    image: teslamate/grafana:${TM_IMAGE_TAG}\n")
	b.WriteString("    restart: always\n")
	b.WriteString("    depends_on:\n      - database\n")
	b.WriteString("    environment:\n")
	writeEnvRefs(&b, []string{
		"DATABASE_USER=${TM_DB_USER}",
		"DATABASE_PASS=${TM_DB_PASS}",
		"DATABASE_NAME=${TM_DB_NAME}",
		"DATABASE_HOST=database",
		"GF_SECURITY_ADMIN_USER=${GRAFANA_USER}",
		"GF_SECURITY_ADMIN_PASSWORD=${GRAFANA_PW}",
		"GF_AUTH_ANONYMOUS_ENABLED=false",
	})
	b.WriteString("    ports:\n")
	fmt.Fprintf(&b, "      - \"${TM_BIND}:${TM_GRAFANA_PORT}:3000\"\n")
	b.WriteString("    volumes:\n      - teslamate-grafana-data:/var/lib/grafana\n")
	return b.String()
}

func renderMosquitto(s Spec) string {
	var b strings.Builder
	b.WriteString("\n  mosquitto:\n")
	b.WriteString("    image: eclipse-mosquitto:2\n")
	b.WriteString("    restart: always\n")
	b.WriteString("    command: mosquitto -c /mosquitto-no-auth.conf\n")
	b.WriteString("    ports:\n")
	fmt.Fprintf(&b, "      - \"${TM_BIND}:${TM_MQTT_PORT}:1883\"\n")
	b.WriteString("    volumes:\n      - mosquitto-conf:/mosquitto/config\n      - mosquitto-data:/mosquitto/data\n")
	return b.String()
}

func writeEnvRefs(b *strings.Builder, refs []string) {
	for _, r := range refs {
		fmt.Fprintf(b, "      - %s\n", r)
	}
}

// HideSecrets replaces every secret value in a rendered env file so the API can
// show a preview without leaking them.
func HideSecrets(env string, secrets ...string) string {
	for _, s := range secrets {
		if s == "" {
			continue
		}
		env = strings.ReplaceAll(env, s, "***")
		env = strings.ReplaceAll(env, quoteEnv(s), "***")
	}
	return env
}

// Checksum returns a stable digest used to detect remote drift.
func Checksum(composeBody string) string {
	sum := sha256.Sum256([]byte(composeBody))
	return hex.EncodeToString(sum[:])
}

// ProjectName is the compose project name for an instance.
func ProjectName(slug string) string { return "1mate-" + slug }

// DefaultBaseDir is where instance files live on the remote host.
func DefaultBaseDir(slug string) string { return "/opt/1mate/instances/" + slug }

func sortStrings(s []string) {
	sort.Strings(s)
}

// Command returns the compose invocation prefix for the observed kind.
func Command(kind model.ComposeKind) (string, bool) {
	switch kind {
	case model.ComposePluginV2:
		return "docker compose", true
	case model.ComposeStandaloneV2, model.ComposeStandaloneV1:
		return "docker-compose", true
	}
	return "", false
}
