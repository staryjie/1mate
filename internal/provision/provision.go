package provision

import (
	"errors"
	"fmt"
	"regexp"
	"strings"

	"1mate/internal/model"
)

// Strategy selects how Docker/Compose gets installed.
type Strategy string

const (
	// StrategyRepo installs from the distribution's Docker package repository.
	// It is the default and installs the v2 compose plugin.
	StrategyRepo Strategy = "repo"
	// StrategyComposeOnly only ensures a v2 Compose is available, leaving the
	// engine untouched.
	StrategyComposeOnly Strategy = "compose_only"
	// StrategyScript runs Docker's convenience installer.
	StrategyScript Strategy = "script"
)

// Options controls the generated installer.
type Options struct {
	Strategy      Strategy
	DockerVersion string
	Mirror        string // "", "Aliyun", "AzureChinaCloud"
	ComposeVersion string
	ComposeURLBase string
	ComposeOnly   bool
	RegistryMirrors []string
	RequireV2     bool
}

var (
	versionPattern = regexp.MustCompile(`^[0-9]+(\.[0-9]+){0,2}$`)
	mirrorPattern  = regexp.MustCompile(`^[A-Za-z0-9._-]*$`)
	urlPattern     = regexp.MustCompile(`^https?://[A-Za-z0-9._:/%-]+$`)
)

// Validate rejects anything that could escape the generated script.
func (o Options) Validate() error {
	switch o.Strategy {
	case StrategyRepo, StrategyComposeOnly, StrategyScript:
	default:
		return errors.New("strategy must be repo, compose_only or script")
	}
	if o.DockerVersion != "" && !versionPattern.MatchString(o.DockerVersion) {
		return errors.New("docker version must look like 27.3.1")
	}
	if o.ComposeVersion != "" && !versionPattern.MatchString(o.ComposeVersion) {
		return errors.New("compose version must look like 2.29.7")
	}
	switch o.Mirror {
	case "", "Aliyun", "AzureChinaCloud":
	default:
		return errors.New("mirror must be Aliyun or AzureChinaCloud")
	}
	if o.ComposeURLBase != "" && !urlPattern.MatchString(o.ComposeURLBase) {
		return errors.New("compose download base must be an http(s) URL")
	}
	for _, m := range o.RegistryMirrors {
		if !urlPattern.MatchString(m) {
			return errors.New("registry mirror must be an http(s) URL")
		}
	}
	return nil
}

// DefaultOptions returns a conservative installer that only fills gaps and
// always prefers Compose v2.
func DefaultOptions() Options {
	return Options{
		Strategy:       StrategyRepo,
		ComposeVersion: model.DefaultComposeVersion,
		ComposeURLBase: "https://github.com/docker/compose/releases/download",
	}
}

// Script renders a POSIX shell installer. It is idempotent: an already
// satisfied host exits successfully without changing anything, and an existing
// Compose v1 binary is never removed.
func Script(o Options) (string, error) {
	if err := o.Validate(); err != nil {
		return "", err
	}
	if o.ComposeVersion == "" {
		o.ComposeVersion = model.DefaultComposeVersion
	}
	if o.ComposeURLBase == "" {
		o.ComposeURLBase = "https://github.com/docker/compose/releases/download"
	}

	var b strings.Builder
	b.WriteString("#!/bin/sh\n")
	b.WriteString("# Generated by 1mate. Idempotent Docker/Compose installer.\n")
	b.WriteString("# It never removes an existing Compose v1 binary and never logs secrets.\n")
	b.WriteString("set -eu\n\n")
	fmt.Fprintf(&b, "COMPOSE_VERSION=%s\n", shQuote(o.ComposeVersion))
	fmt.Fprintf(&b, "COMPOSE_URL_BASE=%s\n", shQuote(strings.TrimRight(o.ComposeURLBase, "/")))
	fmt.Fprintf(&b, "MIRROR=%s\n", shQuote(o.Mirror))
	fmt.Fprintf(&b, "DOCKER_VERSION=%s\n", shQuote(o.DockerVersion))
	fmt.Fprintf(&b, "MANAGE_ENGINE=%s\n", boolShell(o.Strategy != StrategyComposeOnly && !o.ComposeOnly))
	b.WriteString("MANAGE_COMPOSE=1\n")
	fmt.Fprintf(&b, "REQUIRE_V2=%s\n", boolShell(o.RequireV2 || o.Strategy != StrategyRepo))
	mirrors := make([]string, 0, len(o.RegistryMirrors))
	for _, m := range o.RegistryMirrors {
		mirrors = append(mirrors, m)
	}
	fmt.Fprintf(&b, "REGISTRY_MIRRORS=%s\n\n", shQuote(strings.Join(mirrors, ",")))
	b.WriteString(baseHelpers)
	if o.Strategy == StrategyScript {
		b.WriteString("if [ \"$MANAGE_ENGINE\" = \"1\" ]; then\n")
		b.WriteString(runConvenienceInstaller)
		b.WriteString("else\n  say 'engine management disabled; only Compose is managed'\nfi\n")
	} else {
		b.WriteString("if [ \"$MANAGE_ENGINE\" = \"1\" ]; then\n")
		b.WriteString(installPackages)
		b.WriteString("else\n  say 'engine management disabled; only Compose is managed'\nfi\n")
	}
	b.WriteString(installComposeBinary)
	b.WriteString(configureDaemon)
	b.WriteString(finishScript)
	return b.String(), nil
}

func boolShell(b bool) string {
	if b {
		return "1"
	}
	return "0"
}

func shQuote(s string) string {
	if s == "" {
		return "''"
	}
	return "'" + strings.ReplaceAll(s, "'", `'"'"'`) + "'"
}

const baseHelpers = `stage() { printf '1MATE_STAGE=%s\n' "$1"; }
say()   { printf '%s\n' "$*"; }
fail()  { printf '1MATE_ERROR=%s\n' "$*" >&2; exit 1; }
have()  { command -v "$1" >/dev/null 2>&1; }
as_root() {
  if [ "$(id -u)" = "0" ]; then
    sh -c "$1"
  elif have sudo && sudo -n true >/dev/null 2>&1; then
    sudo -n sh -c "$1"
  else
    fail "E_NO_PRIVILEGE: root or passwordless sudo is required to install packages"
  fi
}

stage detect
if [ -r /etc/os-release ]; then
  . /etc/os-release
  OS_ID="$ID"; OS_VER="$VERSION_ID"; OS_CODENAME="${VERSION_CODENAME:-$UBUNTU_CODENAME}"
else
  fail "E_UNSUPPORTED_DISTRO: /etc/os-release is missing"
fi
OS_ID=$(printf '%s' "$OS_ID" | tr '[:upper:]' '[:lower:]')
ARCH=$(uname -m)
case "$ARCH" in
  x86_64|amd64) ARCH_PKG=amd64; ARCH_BIN=x86_64 ;;
  aarch64|arm64) ARCH_PKG=arm64; ARCH_BIN=aarch64 ;;
  *) fail "E_UNSUPPORTED_ARCH: $ARCH cannot run the TeslaMate images" ;;
esac
say "detected ${OS_ID} ${OS_VER} (${ARCH})"

stage preflight
FREE_KB=$(df -Pk /var/lib 2>/dev/null | awk 'NR==2 {print $4}')
if [ -n "$FREE_KB" ] && [ "$FREE_KB" -lt 2097152 ]; then
  say "WARNING: less than 2 GB free under /var/lib; the pull may fail"
fi
case "$OS_ID" in
  ubuntu) case "$OS_VER" in 22.04|24.04|24.10|26.04) : ;; *) fail "E_UNSUPPORTED_DISTRO: Ubuntu $OS_VER is not supported for automated install" ;; esac ;;
  debian) case "$OS_VER" in 12|13) : ;; *) fail "E_UNSUPPORTED_DISTRO: Debian $OS_VER is not supported for automated install" ;; esac ;;
  rocky|almalinux|rhel|centos|ol) ;;
  fedora) : ;;
  *) fail "E_UNSUPPORTED_DISTRO: $OS_ID is not supported for automated install" ;;
esac

# Snapshot current versions so the caller can show a before/after diff.
CUR_DOCKER=$(docker --version 2>/dev/null | sed -n 's/^Docker version \([^,]*\),.*/\1/p')
CUR_COMPOSE=$(docker compose version --short 2>/dev/null || true)
say "current docker: ${CUR_DOCKER:-none}"
say "current compose v2: ${CUR_COMPOSE:-none}"

# Already satisfied: keep the host untouched.
if [ "$MANAGE_ENGINE" = "0" ] && docker compose version >/dev/null 2>&1; then
  stage verify
  say "already satisfied: docker compose v$COMPOSE_VERSION is available"
  printf '1MATE_OK=1\n'
  exit 0
fi
if docker info >/dev/null 2>&1 && docker compose version >/dev/null 2>&1; then
  stage verify
  say "already satisfied: docker engine and compose v2 are present"
  docker compose version || true
  printf '1MATE_OK=1\n'
  exit 0
fi
`

const runConvenienceInstaller = `stage install_engine
TMPINSTALL=$(mktemp /tmp/1mate-docker-install.XXXXXX.sh)
trap 'rm -f "$TMPINSTALL"' EXIT
if ! curl -fsSL https://get.docker.com -o "$TMPINSTALL"; then
  fail "E_DOWNLOAD: cannot download the Docker install script (no outbound access?)"
fi
MIRROR_FLAG=""
if [ -n "$MIRROR" ]; then
  MIRROR_FLAG="--mirror $MIRROR"
fi
VERSION_FLAG=""
if [ -n "$DOCKER_VERSION" ]; then
  VERSION_FLAG="--version $DOCKER_VERSION"
fi
say "repository preview:"
as_root "sh $TMPINSTALL --dry-run $MIRROR_FLAG $VERSION_FLAG" || fail "E_INSTALL_ENGINE: dry run failed"
as_root "sh $TMPINSTALL $MIRROR_FLAG $VERSION_FLAG" || fail "E_INSTALL_ENGINE: installer failed"
`

const installPackages = `stage install_engine
if have docker; then
  say "docker CLI already installed; skipping engine packages"
else
  case "$OS_ID" in
    ubuntu|debian)
      PKGS="ca-certificates curl"
      COMPOSE_PKG="docker-compose-plugin"
      REPO_URL="https://download.docker.com"
      case "$MIRROR" in
        Aliyun) REPO_URL="https://mirrors.aliyun.com/docker-ce" ;;
        AzureChinaCloud) REPO_URL="https://mirror.azure.cn/docker-ce" ;;
      esac
      REPO_DIST="$OS_ID"
      # Docker publishes no Raspbian repository; fall back to Debian packages.
      as_root "DEBIAN_FRONTEND=noninteractive apt-get -qq update" || fail "E_INSTALL_ENGINE: apt-get update failed"
      as_root "DEBIAN_FRONTEND=noninteractive apt-get -y -qq install $PKGS" || fail "E_INSTALL_ENGINE: cannot install prerequisites"
      as_root "install -m 0755 -d /etc/apt/keyrings"
      as_root "curl -fsSL '$REPO_URL/linux/$REPO_DIST/gpg' -o /etc/apt/keyrings/docker.asc" || fail "E_REPO: cannot download the repository key"
      as_root "chmod a+r /etc/apt/keyrings/docker.asc"
      LINE="deb [arch=$ARCH_PKG signed-by=/etc/apt/keyrings/docker.asc] $REPO_URL/linux/$REPO_DIST $OS_CODENAME stable"
      as_root "printf '%s\n' \"$LINE\" > /etc/apt/sources.list.d/docker.list"
      as_root "DEBIAN_FRONTEND=noninteractive apt-get -o DPkg::Lock::Timeout=120 -qq update" || fail "E_REPO: apt-get update failed after adding the Docker repository"
      ENGINE_PKGS="docker-ce docker-ce-cli containerd.io docker-compose-plugin docker-buildx-plugin"
      if [ -n "$DOCKER_VERSION" ]; then
        ENGINE_PKGS="docker-ce=$DOCKER_VERSION* docker-ce-cli=$DOCKER_VERSION* containerd.io docker-compose-plugin docker-buildx-plugin"
      fi
      as_root "DEBIAN_FRONTEND=noninteractive apt-get -y -qq -o DPkg::Lock::Timeout=120 install $ENGINE_PKGS" || fail "E_INSTALL_ENGINE: package installation failed"
      ;;
    rocky|almalinux|rhel|centos|ol|fedora)
      REPO_URL="https://download.docker.com"
      case "$MIRROR" in
        Aliyun) REPO_URL="https://mirrors.aliyun.com/docker-ce" ;;
        AzureChinaCloud) REPO_URL="https://mirror.azure.cn/docker-ce" ;;
      esac
      if have dnf; then
        as_root "dnf -y -q install dnf-plugins-core" || fail "E_INSTALL_ENGINE: cannot install dnf-plugins-core"
        as_root "dnf config-manager --add-repo '$REPO_URL/linux/$OS_ID/docker-ce.repo'" || fail "E_REPO: cannot add the Docker repository"
        ENGINE_PKGS="docker-ce docker-ce-cli containerd.io docker-compose-plugin docker-buildx-plugin"
        if [ -n "$DOCKER_VERSION" ]; then
          ENGINE_PKGS="docker-ce-$DOCKER_VERSION docker-ce-cli-$DOCKER_VERSION containerd.io docker-compose-plugin docker-buildx-plugin"
        fi
        as_root "dnf -y -q install $ENGINE_PKGS" || fail "E_INSTALL_ENGINE: package installation failed"
      else
        as_root "yum -y -q install yum-utils" || fail "E_INSTALL_ENGINE: cannot install yum-utils"
        as_root "yum-config-manager --add-repo '$REPO_URL/linux/$OS_ID/docker-ce.repo'" || fail "E_REPO: cannot add the Docker repository"
        as_root "yum -y -q install docker-ce docker-ce-cli containerd.io docker-compose-plugin" || fail "E_INSTALL_ENGINE: package installation failed"
      fi
      ;;
  esac
fi

stage enable_service
if have systemctl; then
  as_root "systemctl enable --now docker" || say "WARNING: could not enable the docker service"
else
  say "no systemd; start the daemon manually if needed"
fi
`

const installComposeBinary = `
if docker compose version >/dev/null 2>&1; then
  stage install_compose
  say "docker compose v2 plugin is already available"
else
  stage install_compose
  say "installing the compose v2 plugin binary"
  INSTALLED=0
  if [ "$MANAGE_COMPOSE" = "1" ]; then
    URL="$COMPOSE_URL_BASE/v$COMPOSE_VERSION/docker-compose-linux-$ARCH_BIN"
    TMPC=$(mktemp /tmp/1mate-compose.XXXXXX)
    if curl -fsSL "$URL" -o "$TMPC"; then
      as_root "install -m 0755 -d /usr/local/lib/docker/cli-plugins"
      as_root "install -m 0755 '$TMPC' /usr/local/lib/docker/cli-plugins/docker-compose" && INSTALLED=1
    elif curl -fsSL "$COMPOSE_URL_BASE/v$COMPOSE_VERSION/docker-compose-$OS_ID-$ARCH_BIN" -o "$TMPC"; then
      as_root "install -m 0755 -d /usr/local/lib/docker/cli-plugins"
      as_root "install -m 0755 '$TMPC' /usr/local/lib/docker/cli-plugins/docker-compose" && INSTALLED=1
    fi
    rm -f "$TMPC"
    if [ "$INSTALLED" = "0" ]; then
      # Standalone v2 binary is still v2; it is never a downgrade to v1.
      URL2="$COMPOSE_URL_BASE/v$COMPOSE_VERSION/docker-compose-linux-$ARCH_BIN"
      TMPC=$(mktemp /tmp/1mate-compose.XXXXXX)
      if curl -fsSL "$URL2" -o "$TMPC"; then
        as_root "install -m 0755 '$TMPC' /usr/local/bin/docker-compose" && INSTALLED=1
      fi
      rm -f "$TMPC"
    fi
  fi
  if [ "$INSTALLED" = "0" ]; then
    say "WARNING: could not obtain a compose v2 binary; falling back to the package manager"
    case "$OS_ID" in
      ubuntu|debian) as_root "DEBIAN_FRONTEND=noninteractive apt-get -y -qq -o DPkg::Lock::Timeout=120 install docker-compose-plugin" || true ;;
      *) as_root "dnf -y -q install docker-compose-plugin" || as_root "yum -y -q install docker-compose-plugin" || true ;;
    esac
  fi
fi
`

const configureDaemon = `
stage configure_registry
if [ -n "$REGISTRY_MIRRORS" ]; then
  MERGED=$(python3 - "$REGISTRY_MIRRORS" <<'PY' 2>/dev/null || true
import json, sys
path = "/etc/docker/daemon.json"
try:
    with open(path) as f:
        data = json.load(f)
except Exception:
    data = {}
if not isinstance(data, dict):
    data = {}
data["registry-mirrors"] = [m for m in sys.argv[1].split(",") if m]
print(json.dumps(data, indent=2))
PY
)
  if [ -n "$MERGED" ]; then
    TMPD=$(mktemp /tmp/1mate-daemon.XXXXXX)
    printf '%s\n' "$MERGED" > "$TMPD"
    as_root "mkdir -p /etc/docker"
    if [ -f /etc/docker/daemon.json ]; then
      as_root "cp -n /etc/docker/daemon.json /etc/docker/daemon.json.1mate-bak" || true
    fi
    as_root "install -m 0644 '$TMPD' /etc/docker/daemon.json" || say "WARNING: could not write daemon.json"
    rm -f "$TMPD"
    if have systemctl; then
      as_root "systemctl reload docker 2>/dev/null || systemctl restart docker" || say "WARNING: could not reload docker"
    fi
  else
    say "WARNING: could not merge registry mirrors (python3 missing); daemon.json left untouched"
  fi
else
  say "no registry mirrors requested"
fi
`

const finishScript = `
stage verify
DOCKER_OK=0
docker --version >/dev/null 2>&1 && DOCKER_OK=1
COMPOSE_OK=0
if docker compose version >/dev/null 2>&1; then
  COMPOSE_OK=1
  CV=$(docker compose version --short 2>/dev/null || docker compose version 2>/dev/null)
  say "docker compose: $CV"
elif docker-compose version >/dev/null 2>&1; then
  CV=$(docker-compose version --short 2>/dev/null || true)
  case "$CV" in
    v2*|2.*) COMPOSE_OK=1 ;;
  esac
  say "docker-compose: $CV"
fi
if [ "$DOCKER_OK" != "1" ]; then fail "E_VERIFY: docker CLI is not runnable after installation"; fi
if [ "$COMPOSE_OK" != "1" ]; then fail "E_VERIFY: no Compose v2 command is available after installation"; fi
if [ "$REQUIRE_V2" = "1" ]; then
  say "compose v2 verified"
fi
printf '1MATE_OK=1\n'
`

// Preview redacts nothing today but is kept as a single place to grow.
func Preview(o Options) (string, error) { return Script(o) }
